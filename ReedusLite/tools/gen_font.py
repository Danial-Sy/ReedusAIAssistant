def encode(table: dict, h: int):
    """[(char, width, rows as ints MSB = leftmost)]"""
    out = []
    for ch, rows in table.items():
        assert len(rows) == h, ch
        w = len(rows[0])
        assert all(len(r) == w for r in rows), ch
        out.append((ch, w, [int(r.replace("#", "1").replace(".", "0"), 2) for r in rows]))
    return out


def cpp(small, big) -> str:
    def esc(c):
        return "\\xB0" if c == "°" else ("\\'" if c == "'" else ("\\\\" if c == "\\" else c))
    lines = ["// generated by ReedusLite/tools/gen_font.py, edit that, not this", "#pragma once",
             "#include <stdint.h>", "", "namespace font {", "",
             "struct Glyph { char ch; uint8_t w; uint8_t rows[7]; };", ""]
    lines.append(f"static const Glyph SMALL[{len(small)}] = {{")
    for ch, w, rows in small:
        lines.append(f"  {{'{esc(ch)}', {w}, {{{', '.join(str(r) for r in rows + [0, 0])}}}}},")
    lines += ["};", f"static const int N_SMALL = {len(small)};", "static const int SMALL_H = 5;", ""]
    lines.append(f"static const Glyph BIG[{len(big)}] = {{")
    for ch, w, rows in big:
        lines.append(f"  {{'{esc(ch)}', {w}, {{{', '.join(str(r) for r in rows)}}}}},")
    lines += ["};", f"static const int N_BIG = {len(big)};", "static const int BIG_H = 7;", "",
              "}  // namespace font", ""]
    return "\n".join(lines)


def js(small, big) -> str:
    def obj(tbl):
        return "{" + ", ".join(f"{json_str(ch)}: [{w}, [{', '.join(map(str, rows))}]]" for ch, w, rows in tbl) + "}"
    return ("/* generated by ReedusLite/tools/gen_font.py, edit that, not this */\n"
            "const Font = {\n"
            f"  SMALL: {obj(small)},\n  SMALL_H: 5,\n"
            f"  BIG: {obj(big)},\n  BIG_H: 7,\n}};\n")


def json_str(c: str) -> str:
    import json
    return json.dumps(c)


def main():
    root = Path(__file__).resolve().parents[2]
    small, big = encode(SMALL, 5), encode(BIG, 7)
    (root / "ReedusLite/firmware/src/font.h").write_text(cpp(small, big), encoding="utf-8")
    (root / "ReedOS/reedos-app/src/js/font.js").write_text(js(small, big), encoding="utf-8")
    print(f"wrote {len(small)} small + {len(big)} big glyphs")


if __name__ == "__main__":
    main()
