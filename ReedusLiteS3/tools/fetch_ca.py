#!/usr/bin/env python3
"""write firmware/src/ca_cert.h: the root certificate your relay's HTTPS chain ends in, so the
S3 checks it's really talking to your relay (not just to anything with a certificate).

    python ReedusLiteS3/tools/fetch_ca.py your-relay.up.railway.app

needs Python 3.13+ (ssl's get_verified_chain). run it again if Railway ever changes CA; the
S3 will fail to connect and say so on the serial monitor if the root no longer matches.
"""
from __future__ import annotations

import socket
import ssl
import sys
from datetime import date
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "firmware" / "src" / "ca_cert.h"


def root_pem(host: str, port: int = 443) -> tuple[str, str]:
    ctx = ssl.create_default_context()
    with socket.create_connection((host, port), timeout=10) as raw:
        with ctx.wrap_socket(raw, server_hostname=host) as tls:
            if not hasattr(tls, "get_verified_chain"):
                raise SystemExit("needs Python 3.13 or newer (ssl.SSLSocket.get_verified_chain)")
            chain = tls.get_verified_chain()
    der = chain[-1]
    der = der if isinstance(der, (bytes, bytearray)) else der.public_bytes(ssl._ssl.ENCODING_DER)
    pem = ssl.DER_cert_to_PEM_cert(bytes(der))
    # the subject of the root, for the comment
    import tempfile
    with tempfile.NamedTemporaryFile("w", suffix=".pem", delete=False) as f:
        f.write(pem)
        name = f.name
    try:
        info = ssl._ssl._test_decode_cert(name)
        subject = ", ".join("=".join(x[0]) for x in info.get("subject", []))
    except Exception:                                            # noqa: BLE001
        subject = "?"
    finally:
        Path(name).unlink(missing_ok=True)
    return pem.strip(), subject


def main() -> None:
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    host = sys.argv[1].removeprefix("https://").removeprefix("wss://").split("/")[0]
    pem, subject = root_pem(host)
    OUT.write_text(
        "// generated by ReedusLiteS3/tools/fetch_ca.py, do not edit (gitignored)\n"
        f"// root CA for {host}: {subject}  ({date.today()})\n"
        "#pragma once\n"
        f"static const char RELAY_CA_PEM[] = R\"PEM(\n{pem}\n)PEM\";\n",
        encoding="utf-8")
    print(f"wrote {OUT}\n  root: {subject}")


if __name__ == "__main__":
    main()
