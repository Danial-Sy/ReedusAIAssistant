"""turn the wake word model (wakeword/models/reedus.tflite + .json) into a C header.

PlatformIO runs this before every build (extra_scripts = pre:tools/embed_wake_model.py) and
writes .pio/build/<env>/generated/wake_model.h, so a retrained model only needs `pio run`.
`custom_wake_model` in platformio.ini picks another .tflite (its .json must sit next to it).
by hand:  python tools/embed_wake_model.py ../wakeword/models/reedus.tflite out.h
"""
import json
import os
import sys


def render(tflite_path):
    with open(tflite_path, "rb") as f:
        blob = f.read()
    with open(os.path.splitext(tflite_path)[0] + ".json") as f:
        manifest = json.load(f)
    micro = manifest["micro"]
    if int(micro.get("feature_step_size", 10)) != 10:
        raise SystemExit(f"{tflite_path}: wake.cpp only does 10 ms feature steps")
    lines = [
        f"// generated by tools/embed_wake_model.py from {os.path.basename(tflite_path)} and its",
        "// manifest. don't edit: retrain or edit the .json, then rebuild",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define WAKE_MODEL_WORD \"{manifest.get('wake_word', '?')}\"",
        f"#define WAKE_MODEL_VERSION {int(manifest.get('version', 0))}",
        f"#define WAKE_MODEL_CUTOFF {float(micro['probability_cutoff']):.4f}f",
        f"#define WAKE_MODEL_WINDOW {int(micro['sliding_window_size'])}",
        f"#define WAKE_MODEL_ARENA {int(micro['tensor_arena_size'])}",
        "",
        f"static const uint32_t WAKE_MODEL_LEN = {len(blob)};",
        "alignas(16) static const uint8_t WAKE_MODEL[] = {",
    ]
    for i in range(0, len(blob), 20):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in blob[i:i + 20]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def write_if_changed(path, text):
    try:
        with open(path) as f:
            if f.read() == text:
                return False
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    return True


if "Import" not in globals():  # run by hand, not by SCons
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    write_if_changed(sys.argv[2], render(sys.argv[1]))
else:
    Import("env")  # noqa: F821
    proj = env.subst("$PROJECT_DIR")  # noqa: F821
    rel = env.GetProjectOption("custom_wake_model", "../wakeword/models/reedus.tflite")  # noqa: F821
    model = os.path.normpath(os.path.join(proj, rel))
    out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
    if write_if_changed(os.path.join(out_dir, "wake_model.h"), render(model)):
        print(f"wake word: embedded {os.path.relpath(model, proj)} ({os.path.getsize(model)} bytes)")
    env.Append(CPPPATH=[out_dir])  # noqa: F821
